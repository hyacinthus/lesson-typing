// Command gen writes config_gen.go with the Supabase project of the web
// app: VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY from the environment,
// else from the repository's env files, in the precedence Vite gives them
// in a production build. It reads those two keys only: .env.local may also
// hold the service-role key, which must never ship in the app.
package main

import (
	"bufio"
	"fmt"
	"log"
	"os"
	"path/filepath"
	"strings"
)

const out = "config_gen.go"

// envFiles are read in order of precedence, relative to this package.
var envFiles = []string{"../../../.env.production.local", "../../../.env.production", "../../../.env.local", "../../../.env"}

func main() {
	log.SetFlags(0)
	url := lookup("VITE_SUPABASE_URL")
	key := lookup("VITE_SUPABASE_ANON_KEY")
	if url == "" || key == "" {
		log.Fatal("config: VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY must be set, in the environment or the repository's .env")
	}
	src := fmt.Sprintf(`// Code generated by go generate from the repository's .env. DO NOT EDIT.

package config

func init() {
	SupabaseURL = %q
	SupabaseAnonKey = %q
}
`, strings.TrimRight(url, "/"), key)
	if err := os.WriteFile(out, []byte(src), 0o644); err != nil {
		log.Fatal(err)
	}
}

// lookup returns the value of key from the environment or the env files.
func lookup(key string) string {
	if v := os.Getenv(key); v != "" {
		return v
	}
	for _, name := range envFiles {
		if v := readEnvFile(filepath.FromSlash(name), key); v != "" {
			return v
		}
	}
	return ""
}

// readEnvFile returns the value of key in a dotenv file, "" when absent.
func readEnvFile(path, key string) string {
	f, err := os.Open(path)
	if err != nil {
		return ""
	}
	defer f.Close()
	scanner := bufio.NewScanner(f)
	for scanner.Scan() {
		line := strings.TrimSpace(scanner.Text())
		name, value, ok := strings.Cut(line, "=")
		if !ok || strings.TrimSpace(strings.TrimPrefix(name, "export ")) != key {
			continue
		}
		value = strings.TrimSpace(value)
		if len(value) >= 2 && (value[0] == '"' || value[0] == '\'') && value[len(value)-1] == value[0] {
			value = value[1 : len(value)-1]
		}
		return value
	}
	return ""
}
